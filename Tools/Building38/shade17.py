"""N17 observed sRGB palettes and the generated GPU shading contract.

Only surface lighting and palette lookup happen here. Positions, coverage,
pixel counts, material labels and silhouettes are never resampled or authored.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

import numpy as np


ROOT = Path(__file__).resolve().parents[2]
CONTRACT_PATH = Path(__file__).with_name("shading17.json")
HLSL_PATH = ROOT / "Assets/Shaders/World/NativeShade17.hlsl"
LUMINANCE = np.array([0.2126729, 0.7151522, 0.0721750], np.float32)
BAND_COUNTS = np.array([4, 4, 3, 4, 4, 4, 4, 4, 4, 4], np.int32)


def contract():
    values = json.loads(CONTRACT_PATH.read_text(encoding="utf-8"))
    if values["version"] != 17 or values["color_space"] != "linear_irradiance_srgb_observed_palette":
        raise ValueError("N17 shading contract version/color space required")
    if len(values["thresholds"]) != 2 or not 0 < values["thresholds"][0] < values["thresholds"][1]:
        raise ValueError("N17 requires two ordered positive lighting thresholds")
    if values["pattern_materials"] != [1] or values["reference_ambient"] != 0:
        raise ValueError("N17 pattern material and zero fixture ambient are fixed")
    return values


def generated_hlsl():
    c = contract()
    digest = hashlib.sha256(CONTRACT_PATH.read_bytes()).hexdigest()
    t0, t1 = (format(float(x), ".9g") for x in c["thresholds"])
    light = ", ".join(format(float(x), ".9g") for x in c["reference_light_unity"])
    edge = ", ".join(format(float(x) / 255, ".9g") for x in c["edge_black_srgb"])
    offsets = "\n".join(f"    if (material == {int(key)}u) column += {float(value):.1f};"
                        for key, value in sorted(c.get("band_offsets", {}).items()))
    return f'''// Generated by Tools/Building38/shade17.py from shading17.json.
// Contract SHA256: {digest}
#ifndef FANTASY_NATIVE_SHADE_17_INCLUDED
#define FANTASY_NATIVE_SHADE_17_INCLUDED

static const float3 Native17ReferenceLightOS = float3({light});
static const float3 Native17EdgeBlackSRGB = float3({edge});
static const float3 Native17Luminance = float3(0.2126729, 0.7151522, 0.0721750);
static const float Native17CreaseColumn = {float(c["crease_column"]):.1f};

float Native17LightingBand(float luminance)
{{
    return (luminance >= {t0} ? 1.0 : 0.0) + (luminance >= {t1} ? 1.0 : 0.0);
}}

float Native17PaletteColumn(uint material, uint pattern, float band, float bandCount)
{{
    float column = material == 1u ? (float)pattern + band - {float(c["pattern_band_offset"]):.1f} : band;
{offsets}
    return clamp(column, 0.0, bandCount - 1.0);
}}

float3 Native17LightTint(float3 irradiance, float luminance)
{{
    return floor(clamp(irradiance / max(luminance, 0.000001), 0.0, 2.0) * {float(c["tint_intervals"]):.1f} + 0.5) / {float(c["tint_intervals"]):.1f};
}}
#endif
'''


def verify_contract():
    """Reject a GPU include that no longer represents the frozen JSON input."""
    actual = HLSL_PATH.read_text(encoding="utf-8").replace("\r\n", "\n")
    if actual != generated_hlsl():
        raise ValueError("NativeShade17.hlsl differs from shading17.json: regenerate explicitly")
    return hashlib.sha256(CONTRACT_PATH.read_bytes()).hexdigest()


def srgb_to_linear(value):
    v = np.asarray(value, np.float32)
    return np.where(v <= .04045, v / 12.92, ((v + .055) / 1.055) ** 2.4)


def linear_to_srgb(value):
    v = np.clip(np.asarray(value, np.float32), 0, 1)
    return np.where(v <= .0031308, v * 12.92, 1.055 * v ** (1 / 2.4) - .055)


def shade_linear(material_uint8, palette_uint8, irradiance):
    """Mirror the GPU shade operation; RGB output is linear, alpha is coverage."""
    c = contract()
    m = np.asarray(material_uint8)
    palette = np.asarray(palette_uint8)
    if m.dtype != np.uint8 or m.ndim != 3 or m.shape[-1] != 4:
        raise ValueError("Material input must be HxWx4 uint8")
    if palette.dtype != np.uint8 or palette.shape != (10, 4, 3):
        raise ValueError("Palette input must be 10x4x3 uint8 observed sRGB")
    light = np.broadcast_to(np.asarray(irradiance, np.float32), (*m.shape[:2], 3))
    if not np.isfinite(light).all():
        raise ValueError("Finite linear irradiance required")
    light = np.maximum(light, 0)
    luminance = np.maximum(np.sum(light * LUMINANCE, axis=-1), 0)
    band = np.zeros(m.shape[:2], np.int32)
    for threshold in c["thresholds"]:
        band += luminance >= np.float32(threshold)
    ids = m[..., 0].astype(np.int32)
    row = np.clip(ids - 1, 0, 9)
    column = np.where(ids == 1, m[..., 1].astype(np.int32) + band - c["pattern_band_offset"], band)
    for key, value in c.get("band_offsets", {}).items():
        column = np.where(ids == int(key), column + int(value), column)
    column = np.clip(column, 0, BAND_COUNTS[row] - 1)
    column = np.where(m[..., 2] == 3, c["crease_column"], column)
    color = srgb_to_linear(palette[row, column].astype(np.float32) / 255)
    intervals = np.float32(c["tint_intervals"])
    tint = np.floor(np.clip(light / np.maximum(luminance[..., None], np.float32(.000001)), 0, 2) * intervals + .5) / intervals
    color = np.clip(color * tint, 0, 1)
    strong = (m[..., 2] == 1) | (m[..., 2] == 2)
    color[strong] = srgb_to_linear(np.asarray(c["edge_black_srgb"], np.float32) / 255)
    covered = (m[..., 3] >= 128) & (ids >= 1) & (ids <= 10)
    color[(luminance <= .000001) | ~covered] = 0
    alpha = np.where(covered, m[..., 3].astype(np.float32) / 255, 0)
    return np.concatenate((color, alpha[..., None]), -1).astype(np.float32)


def shade_srgb(material_uint8, palette_uint8, normals, reference_light=None):
    """Return native HxWx4 RGBA8 under the shared neutral reference fixture."""
    verify_contract()
    c = contract()
    normal = np.asarray(normals, np.float32)
    if normal.shape != (*np.asarray(material_uint8).shape[:2], 3) or not np.isfinite(normal).all():
        raise ValueError("Finite HxWx3 native normals required")
    direction = np.asarray(c["reference_light_unity"] if reference_light is None else reference_light, np.float32)
    if direction.shape != (3,) or not np.isfinite(direction).all() or np.linalg.norm(direction) <= 0:
        raise ValueError("Finite nonzero fixture direction required")
    direction /= np.linalg.norm(direction)
    brightness = np.clip(np.sum(normal * direction, -1), 0, 1)
    irradiance = np.repeat(brightness[..., None], 3, axis=-1)
    linear = shade_linear(material_uint8, palette_uint8, irradiance)
    rgba = np.concatenate((linear_to_srgb(linear[..., :3]), linear[..., 3:4]), -1)
    return np.floor(np.clip(rgba, 0, 1) * 255 + .5).astype(np.uint8)
